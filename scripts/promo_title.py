"""Единое правило очистки названий объектов от рекламных хвостов.

В постах Telegram к названию часто дописывают промо: «🛎 РАННЕЕ БРОНИРОВАНИЕ
2027 🛎», «🪵скидка 10% на последние денёчки июля🪵». В названии объекта на сайте
(карточка каталога, заголовок страницы, <title>, og:title, микроразметка) такой
хвост не нужен: он устаревает, ломает вёрстку и портит поисковую выдачу.

Модуль общий для генераторов каталога и страниц объектов, чтобы правило не
разъезжалось между ними.
"""
from __future__ import annotations

import re

# Маркер начала рекламного хвоста: всё от него и до конца строки отбрасывается.
PROMO_TAIL_RX = re.compile(
    r"скидк|акци|раннее\s+бронирован|спецпредлож|распродаж|успей|только\s+до\b",
    re.IGNORECASE,
)

# Хвостовой мусор перед отброшенной частью: пробелы, тире, двоеточия, эмодзи.
TAIL_TRIM_RX = re.compile("[\\s\\-–—:,·|" "\U0001f000-\U0001faff☀-➿⬀-⯿️]+$")


def strip_promo_tail(title: str) -> str:
    """Название без рекламного хвоста.

    Если после обрезки ничего не остаётся (название целиком промо) — возвращаем
    исходную строку, чтобы объект не потерял имя.
    """
    text = str(title or "")
    match = PROMO_TAIL_RX.search(text)
    if not match:
        return text
    cleaned = TAIL_TRIM_RX.sub("", text[: match.start()]).strip()
    return cleaned or text

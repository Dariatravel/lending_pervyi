def asset_version() -> str:
    match = re.search(
        r'const\s+ASSET_VERSION\s*=\s*"([^"]+)"',
        (ROOT / "scripts.js").read_text(encoding="utf-8"),
    )
    if not match:
        raise RuntimeError("Не найден ASSET_VERSION в scripts.js")
    return match.group(1)


